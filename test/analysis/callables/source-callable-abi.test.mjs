import assert from "node:assert/strict";
import test from "node:test";
import { compileCsharpSource, assertCsharpCompilationSucceeded } from "../../helpers/direct-csharp-session.mjs";
import { csharpProgramSourceFiles } from "../../helpers/program-source-files.mjs";
import { selectCsharpProjectConstructorAbi } from "../../../dist/analysis/callables/calls/source-callable-abi.js";

test("destructured Error parameters publish the original checked native slot before binding reads", () => {
  const compiled = compileCsharpSource({ sourceText: `
    export function read({ message: renamed }: Error): string { return renamed; }
  ` });
  assertCsharpCompilationSucceeded(compiled);
  const { program } = compiled.result;
  const { source } = program;
  const declaration = source.navigation.nodes.find(node => source.ast.is.IsFunctionDeclaration(node) && source.ast.text(source.ast.name(node)) === "read");
  assert.equal(declaration !== undefined, true, "one authored callable owns the binding input");
  const parameter = source.ast.parameters(declaration)[0];
  const checked = source.semantics.forNode(declaration).types.declarationSignatureInfo(declaration).parameters[0];
  const published = program.records.callableDeclaration.get(declaration)?.contract.nativeParameters;
  assert.equal(published?.length === 1 && published[0].sourceParameter === parameter && checked.declaration === parameter, true,
    "the actual unique declaration slot is not reconstructed from a destructured variable name");
  const carrier = published[0].targetParameter.type;
  assert.equal(carrier.kind === "target-named" && (carrier.id === "System.Exception" || carrier.id.endsWith("::System.Exception")), true,
    "the natural readonly formal keeps its exact native Exception input");
  const body = program.records.callableParameter.get(parameter)?.carrier;
  assert.equal(body === carrier || body?.kind === carrier.kind && body.id === carrier.id, true,
    "the body and final native ABI consume the same published formal identity");
});

test("source receiver annotations do not change generated callable, class or interface ABI", () => {
  const sourceText = `
    interface Reader { read(RECEIVERvalue: number): number; }
    abstract class Base { abstract read(RECEIVERvalue: number): number; }
    class Box extends Base implements Reader {
      private stored: number;
      constructor(value: number) { super(); this.stored = value; }
      read(RECEIVERvalue: number): number { return value + 1; }
      readStored(value: number): number { return this.stored + value; }
      get value(): number { return this.stored; }
      set value(value: number) { this.stored = value; }
    }
    function bump(RECEIVERvalue: number): number { return value + 1; }
    export function run(): number { const box = new Box(4); box.value = bump(box.value); return box.read(2) + box.readStored(2); }
  `;
  const plain = compileCsharpSource({ sourceText: sourceText.replaceAll("RECEIVER", "") });
  const annotated = compileCsharpSource({ sourceText: sourceText.replaceAll("RECEIVER", "this: void, ") });
  assertCsharpCompilationSucceeded(plain);
  assertCsharpCompilationSucceeded(annotated);
  assert.equal([...plain.artifacts.values()].join("\n") === [...annotated.artifacts.values()].join("\n"), true,
    "erasing source receiver annotations changes neither native parameter order nor generated bytes");
  const program = annotated.result.program;
  const { ast } = program.source;
  const nodes = [];
  const visit = node => { nodes.push(node); ast.forEachChild(node, visit); };
  csharpProgramSourceFiles(program).forEach(visit);
  const signatures = nodes.filter(node => ast.is.IsMethodSignatureDeclaration(node));
  assert.equal(signatures.length, 1, "the bodyless interface signature remains checked");
  for (const declaration of signatures) {
    const contract = program.records.callableDispatch.get(declaration)?.implementation;
    const [receiver, value] = ast.parameters(declaration);
    assert.equal(contract?.kind === "source" && contract.parameters.length === 1 &&
      contract.parameters[0] === value && !contract.parameters.includes(receiver), true,
    "a bodyless declaration reads the same sealed source-value vector");
    assert.equal(contract.nativeParameters.length === 1 && contract.nativeParameters[0].sourceParameter === value, true,
      "the exact native slot retains its original source parameter");
    assert.equal(Object.isFrozen(contract) && Object.isFrozen(contract.parameters) && Object.isFrozen(contract.nativeParameters), true,
      "the published ABI contains frozen data, not a receiver filter or service");
  }
});

test("native-only constructor contracts contain no fabricated source vector", () => {
  const carrier = Object.freeze({ kind: "source-primitive", name: "int32" });
  const owner = Object.freeze({});
  const selected = selectCsharpProjectConstructorAbi({ definition: { declaration: owner },
    source: { parameters: [] }, targetMember: { declaringType: carrier, parameters: [] } });
  assert.equal(selected?.kind, "native", "a native-only constructor is explicitly discriminated");
  assert.equal(Object.hasOwn(selected, "parameters"), false, "absence of source syntax is not an empty authored parameter list");
  assert.equal(selected.nativeParameters.length, 0, "the genuine zero native slots are preserved");
  assert.equal(Object.isFrozen(selected) && Object.isFrozen(selected.nativeParameters), true, "the native contract is frozen before publication");
  assert.equal(selectCsharpProjectConstructorAbi({ definition: { declaration: owner }, source: { parameters: [] },
    targetMember: { parameters: [] } }) === undefined, true, "missing native return evidence does not manufacture a contract");
});

test("native callable and class emission transport the original canonical contracts", () => {
  const compiled = compileCsharpSource({ sourceText: `
    class Box {
      constructor(readonly value: number) {}
      read(input: number): number { return this.value + input; }
    }
    export function run(): number { return new Box(4).read(2); }
  ` });
  assertCsharpCompilationSucceeded(compiled);
  const program = compiled.result.program;
  const { ast } = program.source;
  const nodes = [];
  const visit = node => { nodes.push(node); ast.forEachChild(node, visit); };
  csharpProgramSourceFiles(program).forEach(visit);
  const declaration = nodes.find(node => ast.is.IsClassDeclaration(node));
  const constructor = nodes.find(node => ast.is.IsConstructorDeclaration(node));
  const method = nodes.find(node => ast.is.IsMethodDeclaration(node));
  const emitted = program.records.nativeClass.get(declaration);
  assert.equal(emitted.constructorContracts.length, 1, "the single authored constructor is closed before publication");
  const contract = emitted.constructorContracts[0];
  assert.equal(contract.kind === "source" && contract.sourceDeclaration === constructor, true,
    "the original constructor contract, not a copied source-vector field, is transported");
  assert.equal(contract.parameters[0] === ast.parameters(constructor)[0], true,
    "the original parameter identity survives the native class record");
  assert.equal(Object.isFrozen(emitted.constructorContracts) && Object.isFrozen(contract), true,
    "the class transports immutable existing evidence");
  assert.equal(program.records.callableDeclaration.get(method).contract === program.records.callableDispatch.get(method).implementation, true,
    "body and dispatch consume the identical presealed source contract");
});
